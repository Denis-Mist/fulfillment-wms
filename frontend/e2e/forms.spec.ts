test('товар: обязательные поля, создание, дубль SKU', async ({ page, loginAs }) => {
  await loginAs('seller_owner')
  await page.goto('/seller/products')
  await waitReady(page)
  const save = () => dialog(page).getByRole('button', { name: /Сохранить|Добавить|Создать/ }).last()
  await page.getByRole('button', { name: /Добавить товар/ }).click()
  await save().click()
  await expect(dialog(page).locator('small').first()).toBeVisible()
  const sku = `QA-${Date.now().toString().slice(-6)}`
  const fill = async (s: string) => {
    await page.locator('#pf-sku').fill(s)
    await page.locator('#pf-name').fill('Тестовый товар QA')
    await page.locator('#pf-bc').fill('4600000000001')
    for (const id of ['pf-price', 'pf-w', 'pf-v']) await page.locator(`#${id}`).fill('10')
  }
  await fill(sku)
  await save().click()
  await expect(page.locator('.p-dialog')).toHaveCount(0)
  await expect(page.getByText(sku).first()).toBeVisible()
  await page.getByRole('button', { name: /Добавить товар/ }).click()
  await fill(sku)
  await save().click()
  await expect(page.locator('.p-dialog')).toHaveCount(1)
  await expect(page.getByText(/уже|существует/).first()).toBeVisible()
})

// FBO-поставку создаёт селлер; у ФЦ раздел — только обработка
for (const [role, path] of [['seller_owner', '/seller/fbo']] as const) {
  test(`FBO (${role}): черновик недоступен без данных и создаётся с валидными`, async ({ page, loginAs }) => {
    await loginAs(role)
    await page.goto(path)
    await waitReady(page)
    await page.getByRole('button', { name: /Новая поставка/ }).click()
    const d = dialog(page)
    const create = d.getByRole('button', { name: /Создать черновик/ })
    await expect(create).toBeDisabled()
    const selects = d.locator('.p-select')
    const n = await selects.count()
    for (let i = 0; i < n; i++) {
      await selects.nth(i).click()
      await page.locator('.p-select-option').first().click()
    }
    const qty = d.locator('input.p-inputnumber-input').first()
    await qty.fill('1')
    await qty.blur()
    await expect(create).toBeEnabled()
    await create.click()
    await expect(page.locator('.p-dialog')).toHaveCount(0)
    await expect(toast(page).first()).toBeVisible()
  })
}
